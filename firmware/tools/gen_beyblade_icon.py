"""Generate assets/icons/beyblade.svg: a spinning top seen from above, simplified
from a swirl-blade logo: curved blades around a gear hub, plus two motion swooshes.

Usage: python tools/gen_beyblade_icon.py assets/icons/beyblade.svg
Tweak the constants below to change the shape, then regenerate the bitmap (see main/icons.c).
"""
import math
import sys

C = 12.0                 # centre of the 24x24 view box

BLADES = 5
BLADE_R_IN = 6.0         # blade root
BLADE_R_OUT = 10.0       # blade tip
BLADE_SWEEP = 80         # degrees the leading edge turns from root to tip
BLADE_ROOT_WIDTH = 46    # degrees of the blade root

GEAR_TEETH = 6
GEAR_R_ROOT = 3.3
GEAR_R_TIP = 4.4
GEAR_STROKE = 1.3
CORE_R = 1.7             # solid core

SWOOSH_R = 11.4
SWOOSH_STROKE = 1.4
SWOOSHES = [(195, 290), (15, 110)]   # start/end angles (degrees, clockwise from 3 o'clock)


def pt(r, deg):
    a = math.radians(deg)
    return C + r * math.cos(a), C + r * math.sin(a)


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def poly(points, close=True):
    d = "M" + " L".join(f"{f(x)} {f(y)}" for x, y in points)
    return d + (" Z" if close else "")


def blade(base):
    """Curved wedge: the leading edge spirals out to the tip; the blade spans a width behind
    it that narrows from BLADE_ROOT_WIDTH at the root to a point at the tip (never crosses)."""
    n = 16
    ts = [i / n for i in range(n + 1)]
    r = lambda t: BLADE_R_IN + (BLADE_R_OUT - BLADE_R_IN) * t
    lead_a = lambda t: base + BLADE_SWEEP * t ** 0.8
    width = lambda t: BLADE_ROOT_WIDTH * (1 - t) ** 0.8
    lead = [pt(r(t), lead_a(t)) for t in ts]
    trail = [pt(r(t), lead_a(t) - width(t)) for t in reversed(ts)]
    return poly(lead + trail[1:])


def gear():
    pts = []
    step = 360 / GEAR_TEETH
    for k in range(GEAR_TEETH):
        a = k * step
        # root, rise, flat top, fall
        pts += [pt(GEAR_R_ROOT, a), pt(GEAR_R_TIP, a + step * 0.12),
                pt(GEAR_R_TIP, a + step * 0.38), pt(GEAR_R_ROOT, a + step * 0.5)]
    return poly(pts)


def arc(r, a0, a1):
    x0, y0 = pt(r, a0)
    x1, y1 = pt(r, a1)
    large = 1 if (a1 - a0) % 360 > 180 else 0
    return f"M{f(x0)} {f(y0)} A{f(r)} {f(r)} 0 {large} 1 {f(x1)} {f(y1)}"


def circle_d(r):
    return f"M{f(C - r)} {f(C)} a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0 a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0"


paths = []
for k in range(BLADES):
    paths.append(f'  <path d="{blade(k * 360 / BLADES - 90)}" fill="currentColor" stroke="none" />')
paths.append(f'  <path d="{gear()}" stroke-width="{GEAR_STROKE}" />')
paths.append(f'  <path d="{circle_d(CORE_R)}" fill="currentColor" stroke="none" />')
for a0, a1 in SWOOSHES:
    paths.append(f'  <path d="{arc(SWOOSH_R, a0, a1)}" stroke-width="{SWOOSH_STROKE}" />')

svg = """<!--
BX Tacho icon: spinning top seen from above. Curved swirl blades around a gear hub with a
solid core, and two motion swooshes. Original design for this project, generated by
tools/gen_beyblade_icon.py. Monochrome (currentColor), 24x24, so it scales and recolours.
Bitmaps are generated with tools/svg_icon_to_c.py (see main/icons.c for the exact command).
-->
<svg
  xmlns="http://www.w3.org/2000/svg"
  width="24"
  height="24"
  viewBox="0 0 24 24"
  fill="none"
  stroke="currentColor"
  stroke-width="2"
  stroke-linecap="round"
  stroke-linejoin="round"
>
""" + "\n".join(paths) + "\n</svg>\n"

open(sys.argv[1], "w", encoding="utf-8", newline="\n").write(svg)
