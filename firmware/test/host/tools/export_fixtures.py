"""Write the host tests' launcher calibrations (fixtures/launcher_cals.h)
from the production database.

Only the four load calibration levels of each board are read: no IDs, MACs,
dates or customer columns, so the header can be committed (production.db
can't). Boards with the same four levels are kept once.

    python tools/export_fixtures.py [path/to/production.db]
"""

import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_DB = HERE.parents[3] / 'production' / 'production.db'
OUT = HERE.parent / 'fixtures' / 'launcher_cals.h'

QUERY = ('SELECT DISTINCT black_load_empty_mv, black_load_loaded_mv, white_load_empty_mv, white_load_loaded_mv '
         'FROM boards WHERE black_load_empty_mv IS NOT NULL AND black_load_loaded_mv IS NOT NULL '
         'AND white_load_empty_mv IS NOT NULL AND white_load_loaded_mv IS NOT NULL '
         'ORDER BY 1, 2, 3, 4')


def main():
    db = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DB
    con = sqlite3.connect(f'file:{db.as_posix()}?mode=ro', uri=True)
    rows = con.execute(QUERY).fetchall()
    con.close()
    lines = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Copyright (C) 2026 Darren Chi',
        '// Generated by tools/export_fixtures.py from the production database: the',
        '// load calibrations saved on the boards made so far (mV), each set once.',
        '// Only these levels, nothing that identifies a board. Regenerate, don\'t edit.',
        '#pragma once',
        '',
        'typedef struct {',
        '    int black_empty, black_loaded, white_empty, white_loaded;',
        '} fixture_cal_t;',
        '',
        'static const fixture_cal_t FIXTURE_CALS[] = {',
    ]
    lines += [f'    {{{be}, {bl}, {we}, {wl}}},' for be, bl, we, wl in rows]
    lines += [
        '};',
        '',
        '#define FIXTURE_CAL_COUNT (sizeof(FIXTURE_CALS) / sizeof(FIXTURE_CALS[0]))',
        '',
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{len(rows)} calibrations -> {OUT}')


if __name__ == '__main__':
    main()
